//go:build ignore

// v5names maps the model type names that pkg/openapi exported at tag v5.2.2 to the
// long generated names on the current tree, and emits the short-name aliases that
// can be restored honestly.
//
// Usage (from the repository root):
//
//	mkdir -p /tmp/v522 && git archive v5.2.2 pkg/openapi | tar -x -C /tmp/v522
//	go run scripts/openapi-compat/v5names.go -old /tmp/v522/pkg/openapi \
//	    -report /tmp/v5names-report.md -write -test pkg/gorp/openapi_compat_v5_test.go
//
// -write replaces the block between the BEGIN/END markers of scripts/openapi-compat/compat.go.tmpl
// and copies the template to pkg/openapi/compat.go; without it the tool only reports.
// The tool reads the current tree without that block, so running it again gives the same result.
//
// Mapping rule. An alias `Old = New` is accepted only when all of these hold:
//
//  1. Old is a model type of v5.2.2 (not Nullable*, Api*Request, *APIService) that
//     no longer resolves on the current tree.
//  2. Exactly one schema key in reportportal-api-docs.json is named Old once its Java
//     package segments are stripped (`com.epam.reportportal.base.reporting.Issue` -> `Issue`,
//     `…model.BulkRQJava.lang.LongCom.epam.…launch.UpdateLaunchRQ` -> `BulkRQLongUpdateLaunchRQ`),
//     or is a nested class whose own name is Old (`…reporting.Issue.ExternalSystemIssue`
//     -> `ExternalSystemIssue`). Two keys with that name mean "ambiguous": no alias.
//     2b. Failing that, Old is restored when every field that had type Old in an already
//     mapped v5.2.2 struct now has one and the same type in the same position
//     (`[]ItemAttributeResource` -> `[]…ReportingAttributeResource` in every struct).
//  3. The Go type generated for that key exists, and the JSON field names of the
//     v5.2.2 struct are a subset of its JSON field names.
//
// Go-level differences that survive the alias (a field whose Go type changed, a
// constructor whose signature changed) are reported, not hidden.
package main

